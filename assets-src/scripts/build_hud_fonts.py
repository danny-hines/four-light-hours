"""Embed the HUD's two web fonts into src/ui/fonts-data.js as base64 (so the single-file build works offline).

Usage (from assets-src/scripts):  python -I build_hud_fonts.py ../raw/fonts_google ../../src/ui/fonts-data.js

Inputs (Google Fonts, latin subset, variable woff2, SIL Open Font License 1.1):
  jost-latin-var.woff2                     Jost, wght 200..600
  cormorant-garamond-italic-latin-var.woff2  Cormorant Garamond Italic, wght 400..600
"""
import base64
import os
import sys

FILES = [
    ("JOST", "jost-latin-var.woff2", "Copyright 2020 The Jost Project Authors (https://github.com/indestructible-type/Jost)"),
    ("CORMORANT_ITALIC", "cormorant-garamond-italic-latin-var.woff2",
     "Copyright 2015 The Cormorant Project Authors (github.com/CatharsisFonts/Cormorant)"),
]


def main(src_dir, out_path):
    lines = [
        "// GENERATED by assets-src/scripts/build_hud_fonts.py — do not edit by hand.",
        "// Web fonts for the HUD, embedded so the single-file build works offline.",
        "// Both fonts: SIL Open Font License 1.1 (https://openfontlicense.org). Licence texts: assets-src/raw/fonts_google/OFL-*.txt",
    ]
    for name, fn, cr in FILES:
        data = open(os.path.join(src_dir, fn), "rb").read()
        lines.append(f"// {fn}: {cr}")
        lines.append(f"export const {name} = '{base64.b64encode(data).decode('ascii')}';")
        print(fn, len(data), "bytes")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
